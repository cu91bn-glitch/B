export const SURVEY_TEMPLATES = T.map(t => ({ key: t.key, kind: t.kind, title: t.title, who: t.who, intro: t.intro, items: t.sections.reduce((n, [, i]) => n + i.length, 0), sections: t.sections.length }));

export function buildTemplate(key: string): Partial<SurveyDefinition> {
  const t = T.find(x => x.key === key);
  if (!t) throw new Error('النموذج غير موجود');
  return {
    title: t.title, audience: t.audience, intro: t.intro, scale: likert, programs: t.programs,
    demographics: [t.audience.includes('|') || t.audience !== 'student' ? role : grade, ...(t.kind === 'أثر' ? [wave] : [])],
    sections: t.sections.map(([name, items], i) => ({
      id: `s${i + 1}`, name,
      items: items.map(text => ({ text, reverse: /أتعرض للسخرية/.test(text) })),
    })),
    extra: t.open ? [{ id: 'open', text: t.open, type: 'text' }] : [],
    settings: { anonymous: true, one_response_per_device: true },
  };
}
